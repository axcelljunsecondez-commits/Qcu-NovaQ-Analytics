import { act, fireEvent, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import { renderWithProviders } from '../../test/test-utils'
import { Tooltip } from './Tooltip'
import { InfoTip } from './InfoTip'

describe('shared tooltip pointer and keyboard boundaries', () => {
  it('does not open from wrapper whitespace', async () => {
    const user = userEvent.setup()
    renderWithProviders(<InfoTip name="Wait" text="Explanation" />)
    const button = screen.getByRole('button', { name: 'About: Wait' })
    await user.hover(button.parentElement as HTMLElement)
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
    await user.hover(button)
    expect(screen.getByRole('tooltip')).toHaveTextContent('Explanation')
    await user.unhover(button)
    await waitFor(() => expect(screen.queryByRole('tooltip')).not.toBeInTheDocument())
  })
  it('does not turn pointer focus into persistent keyboard hover', async () => {
    renderWithProviders(<InfoTip name="Wait" text="Explanation" />)
    const button = screen.getByRole('button', { name: 'About: Wait' })
    fireEvent.pointerDown(button)
    act(() => button.focus())
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
    fireEvent.pointerOver(button)
    expect(screen.getByRole('tooltip')).toBeInTheDocument()
    fireEvent.pointerOut(button, { relatedTarget: document.body })
    await waitFor(() => expect(screen.queryByRole('tooltip')).not.toBeInTheDocument())
    expect(button).toHaveFocus()
  })
  it('lets an outside input receive its first click while dismissing pinned help', async () => {
    const user = userEvent.setup()
    renderWithProviders(<><InfoTip name="Wait" text="Explanation" /><input aria-label="Next field" /></>)
    await user.click(screen.getByRole('button', { name: 'About: Wait' }))
    expect(screen.getByRole('tooltip')).toBeInTheDocument()
    await user.click(screen.getByRole('textbox', { name: 'Next field' }))
    expect(screen.getByRole('textbox', { name: 'Next field' })).toHaveFocus()
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
  })
  it('opens only after a touch activation and closes with the second tap', async () => {
    const user = userEvent.setup()
    renderWithProviders(<InfoTip name="Wait" text="Explanation" />)
    const button = screen.getByRole('button', { name: 'About: Wait' })
    await user.pointer({ keys: '[TouchA>]', target: button })
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
    await user.pointer({ keys: '[/TouchA]', target: button })
    expect(screen.getByRole('tooltip')).toBeInTheDocument()
    await user.pointer([{ keys: '[TouchA>]', target: button }, { keys: '[/TouchA]', target: button }])
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
  })
  it('replaces pinned help when another tooltip opens without moving focus', async () => {
    const user = userEvent.setup()
    renderWithProviders(<><InfoTip name="First" text="First explanation" /><InfoTip name="Second" text="Second explanation" /></>)
    const first = screen.getByRole('button', { name: 'About: First' })
    await user.click(first)
    await user.hover(screen.getByRole('button', { name: 'About: Second' }))
    expect(screen.getAllByRole('tooltip')).toHaveLength(1)
    expect(screen.getByRole('tooltip')).toHaveTextContent('Second explanation')
    expect(first).toHaveFocus()
    expect(first).toHaveAttribute('aria-expanded', 'false')
  })
  it('keeps popup text hoverable and allows its own scroll', async () => {
    const user = userEvent.setup()
    renderWithProviders(<InfoTip name="Wait" text="Explanation" />)
    await user.hover(screen.getByRole('button', { name: 'About: Wait' }))
    const popup = screen.getByRole('tooltip')
    await user.hover(popup)
    fireEvent.scroll(popup)
    expect(popup).toBeInTheDocument()
    await user.unhover(popup)
    await waitFor(() => expect(screen.queryByRole('tooltip')).not.toBeInTheDocument())
  })
  it.each(['scroll', 'resize'])('dismisses on viewport %s instead of leaving a detached popup', async (event) => {
    const user = userEvent.setup()
    renderWithProviders(<InfoTip name="Wait" text="Explanation" />)
    await user.click(screen.getByRole('button', { name: 'About: Wait' }))
    expect(screen.getByRole('tooltip')).toBeInTheDocument()
    fireEvent(window, new Event(event))
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
  })
  it('preserves a name control action, then keeps its clicked hint dismissed', async () => {
    const user = userEvent.setup()
    let calls = 0
    renderWithProviders(<Tooltip label="Account"><button onClick={() => { calls += 1 }}>Account action</button></Tooltip>)
    const button = screen.getByRole('button', { name: 'Account action' })
    await user.hover(button)
    expect(screen.getByTestId('tooltip')).toHaveTextContent('Account')
    await user.click(button)
    expect(calls).toBe(1)
    expect(screen.queryByTestId('tooltip')).not.toBeInTheDocument()
    fireEvent.pointerMove(button)
    expect(screen.queryByTestId('tooltip')).not.toBeInTheDocument()
  })
  it('clears stale popup hover after Escape before the next hover session', async () => {
    const user = userEvent.setup()
    renderWithProviders(<InfoTip name="Wait" text="Explanation" />)
    const button = screen.getByRole('button', { name: 'About: Wait' })
    await user.hover(button)
    await user.hover(screen.getByRole('tooltip'))
    await user.keyboard('{Escape}')
    expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
    await user.hover(button)
    expect(screen.getByRole('tooltip')).toBeInTheDocument()
    await user.unhover(button)
    await waitFor(() => expect(screen.queryByRole('tooltip')).not.toBeInTheDocument())
  })

})
